#!/usr/bin/env python3
"""Derive the failure-experiment configs from the global Java-store config.

config_failure_leader_global.yaml and config_failure_follower_global.yaml are
config_global.yaml with two things replaced:

- the phase schedule: a 30 s warm-up, then 600 s of the normal mix at DAY_LOAD times
  the base's capacity C (read off the base's "# 1C" phase) split into five 120 s phases
  (NormalDay, Failure1, Failure2, Recovery1, Recovered), then a 30 s cool-down, 660 s
  in all. At 0.5 C (the first trial) two failures cost latency and violations only, the
  price never left its floor; 1 C is where losing two of five nodes pushes the
  survivors past the utilization target;
- the failure schedule: fail at 150 s and 270 s from the workload start (120 s and
  240 s into the day), recover at 390 s and 510 s. The leader config fails whichever
  node leads at each failure, the follower config the lowest-numbered healthy follower;
  recoveries bring back the node failed longest, so each node is down for 240 s.

Everything else (topology, SLAs, mixes, C, sMax, the cap, the budgets, the client
settings) is config_global.yaml as is. Java store only: the schedule is rejected with
transport: mongodb. The generated files say so in their first line; edit this script or
the base and regenerate:

  python3 make_failure_configs.py
"""

import re
import sys

BASE = "config_global.yaml"
OUTPUTS = [("config_failure_leader_global.yaml", "LEADER"), ("config_failure_follower_global.yaml", "FOLLOWER")]
WINDOW_S = 120
WINDOWS = ["NormalDay", "Failure1", "Failure2", "Recovery1", "Recovered"]
WARMUP_S = 30
COOLDOWN_S = 30
EVENTS = [(150, "fail"), (270, "fail"), (390, "recover"), (510, "recover")]
DAY_LOAD = 1.0  # fraction of C the whole day runs at


def replace_once(text, pattern, replacement, what):
    matches = list(re.finditer(pattern, text, flags=re.MULTILINE))
    if len(matches) != 1:
        sys.exit(f"{what}: expected exactly one match, found {len(matches)}")
    m = matches[0]
    return text[:m.start()] + replacement + text[m.end():]


def derive(base_text, role, out_name):
    m = re.search(r"^\s+totalTPS: (\d+)\s*# 1C\b", base_text, flags=re.MULTILINE)
    if not m:
        sys.exit("no phase marked '# 1C' in the base, so C cannot be read off it")
    capacity = int(m.group(1))
    tps = round(capacity * DAY_LOAD)

    def phase(name, duration, comment):
        return (f"    - name: {name:16s}# {comment}\n      durationSeconds: {duration}\n"
                f"      totalTPS: {tps}     # {DAY_LOAD:g}C, normal mix\n      mix: normal\n")

    comments = {
        "NormalDay": "all five nodes healthy",
        "Failure1": f"one node failed at {EVENTS[0][0]} s ({role.lower()})",
        "Failure2": f"two nodes failed from {EVENTS[1][0]} s: exactly a majority remains",
        "Recovery1": f"first recovery at {EVENTS[2][0]} s (the node failed longest); one node still failed",
        "Recovered": f"second recovery at {EVENTS[3][0]} s: all five nodes healthy again",
    }
    phases = phase("WarmUp", WARMUP_S, "warm up the cluster")
    for name in WINDOWS:
        phases += phase(name, WINDOW_S, comments[name])
    phases += phase("CoolDown", COOLDOWN_S, "cool down to handle shutdown delays")
    text = replace_once(base_text, r"^  phases:\n(?:(?:    .*|)\n)+?(?=^# Which store)",
                        "  phases:\n" + phases + "\n", "workload.phases")

    schedule = "failureSchedule:\n"
    for at, action in EVENTS:
        if action == "fail":
            schedule += f"  - {{ atSeconds: {at}, action: fail, target: {role} }}\n"
        else:
            schedule += f"  - {{ atSeconds: {at}, action: recover }}\n"
    text = replace_once(text, r"^failureSchedule: \[\]\n", schedule, "failureSchedule")

    header = [
        f"# GENERATED by make_failure_configs.py from {BASE}; do not edit by hand, edit the base or the",
        f"# generator and regenerate. The failure experiment, {role.lower()} variant: a {WARMUP_S} s warm-up, "
        f"{len(WINDOWS) * WINDOW_S} s of the",
        f"# normal mix at {DAY_LOAD:g}C in {len(WINDOWS)} windows of {WINDOW_S} s, a {COOLDOWN_S} s cool-down; failures at "
        f"{EVENTS[0][0]} s and {EVENTS[1][0]} s from the workload",
        f"# start ({role}: " + ("whoever leads at that moment" if role == "LEADER" else "the lowest-numbered healthy follower")
        + f"), recoveries at {EVENTS[2][0]} s and {EVENTS[3][0]} s (first failed, first recovered).",
        "# Topology, SLAs, mixes, C, sMax, cap and budgets are the base's. Java store only.",
    ]
    return "\n".join(header) + "\n\n" + text


def main():
    with open(BASE) as f:
        base_text = f.read()
    for out_name, role in OUTPUTS:
        with open(out_name, "w") as f:
            f.write(derive(base_text, role, out_name))
        print(f"wrote {out_name}: {role} failures at {EVENTS[0][0]} s and {EVENTS[1][0]} s, "
              f"recoveries at {EVENTS[2][0]} s and {EVENTS[3][0]} s")


if __name__ == "__main__":
    main()
